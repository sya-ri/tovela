#!/usr/bin/env bash
set -euo pipefail

manifest=internal/frprelease/release.go
current=$(sed -nE 's/^const Version = "([0-9]+\.[0-9]+\.[0-9]+)"$/\1/p' "$manifest")
if [[ -z "$current" ]]; then
  echo "Could not read the pinned FRP version." >&2
  exit 1
fi

release=$(cat)
version=$(jq -er '
  select(.draft == false and .prerelease == false)
  | .tag_name
  | select(test("^v(0|[1-9][0-9]*)(\\.(0|[1-9][0-9]*)){2}$"))
  | ltrimstr("v")
' <<< "$release")
if [[ -z "$version" ]]; then
  echo "Could not read a stable FRP release version." >&2
  exit 1
fi
if [[ "$version" == "$current" || $(printf '%s\n' "$current" "$version" | sort -V | tail -n 1) != "$version" ]]; then
  echo "FRP $current is up to date."
  exit 0
fi

updated=$(mktemp "$manifest.XXXXXX")
trap 'rm -f "$updated"' EXIT
{
  printf '// Code generated by scripts/update-frp.sh. DO NOT EDIT.\n\n'
  printf 'package frprelease\n\nconst Version = "%s"\n\n' "$version"
  while read -r constant target; do
    archive="frp_${version}_${target}"
    if ! digest=$(jq -er --arg archive "$archive" '
      [.assets[] | select(.name == $archive and .state == "uploaded")]
      | select(length == 1)
      | .[0].digest
      | select(type == "string" and test("^sha256:[0-9a-f]{64}$"))
      | ltrimstr("sha256:")
    ' <<< "$release"); then
      echo "Missing valid SHA-256 digest for $archive." >&2
      exit 1
    fi
    printf 'const %s = "%s"\n' "$constant" "$digest"
  done <<'ASSETS'
DarwinAMD64SHA256 darwin_amd64.tar.gz
DarwinARM64SHA256 darwin_arm64.tar.gz
LinuxAMD64SHA256 linux_amd64.tar.gz
LinuxARM64SHA256 linux_arm64.tar.gz
WindowsAMD64SHA256 windows_amd64.zip
WindowsARM64SHA256 windows_arm64.zip
ASSETS
} > "$updated"
chmod 0644 "$updated"
mv "$updated" "$manifest"
echo "Updated FRP from $current to $version."
